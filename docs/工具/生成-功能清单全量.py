HDR_FILL = PatternFill("solid", fgColor="2F3B52")
TITLE_FILL = PatternFill("solid", fgColor="E8ECF3")
ZEBRA_FILL = PatternFill("solid", fgColor="F7F7F4")
NEW_FILL = PatternFill("solid", fgColor="E4F1E4")
ITER_FILL = PatternFill("solid", fgColor="FBEEDC")
THIN = Side(style="thin", color="C9CDD4")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)

HDR_FONT = Font(bold=True, color="FFFFFF", size=11)
TITLE_FONT = Font(bold=True, size=11)
BODY_FONT = Font(size=10)
NEW_FONT = Font(size=10, bold=True, color="1E6B34")
ITER_FONT = Font(size=10, bold=True, color="9A5B00")

WRAP = Alignment(wrap_text=True, vertical="top")
CENTER = Alignment(wrap_text=True, vertical="center", horizontal="center")


def build_sheet(wb, name, title, headers, widths, rows, status_col=None):
    ws = wb.create_sheet(title=name)
    ncol = len(headers)

    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncol)
    c = ws.cell(row=1, column=1, value=title)
    c.font = TITLE_FONT
    c.fill = TITLE_FILL
    c.alignment = Alignment(wrap_text=True, vertical="center")
    ws.row_dimensions[1].height = 46

    for j, h in enumerate(headers, 1):
        c = ws.cell(row=2, column=j, value=h)
        c.font = HDR_FONT
        c.fill = HDR_FILL
        c.alignment = CENTER
        c.border = BORDER
        ws.column_dimensions[get_column_letter(j)].width = widths[j - 1]
    ws.row_dimensions[2].height = 22
    ws.freeze_panes = "A3"

    for i, row in enumerate(rows):
        r = i + 3
        fill = ZEBRA_FILL if i % 2 else None
        for j, v in enumerate(row, 1):
            c = ws.cell(row=r, column=j, value=v)
            c.font = BODY_FONT
            c.alignment = WRAP
            c.border = BORDER
            if fill:
                c.fill = fill
        if status_col is not None:
            sc = ws.cell(row=r, column=status_col)
            if isinstance(sc.value, str) and sc.value.startswith("新增"):
                sc.fill = NEW_FILL
                sc.font = NEW_FONT
            elif isinstance(sc.value, str) and sc.value.startswith("迭代"):
                sc.fill = ITER_FILL
                sc.font = ITER_FONT
            sc.alignment = CENTER
    return ws


