def main():
    doc = Document(TPL)
    body = doc.element.body
    paras = list(body.iter(qn("w:p")))
    skeleton = next(p for p in paras if "用 200" in para_text(p))

    removed = 0
    for p in list(body.iter(qn("w:p"))):
        if is_gray_instruction(p):
            p.getparent().remove(p)
            removed += 1

    filled = []
    for p in list(body.iter(qn("w:p"))):
        txt = para_text(p).strip()
        new_text = None
        for key, val in COVER.items():
            if txt.startswith(key + "："):
                new_text = val
                filled.append(key)
                break
        if new_text is None and txt in TITLE_FIX:
            new_text = TITLE_FIX[txt]
            filled.append("标题")
        if new_text is not None:
            for r in list(p.findall(qn("w:r"))):
                p.remove(r)
            r = p.makeelement(qn("w:r"), {})
            rpr = r.makeelement(qn("w:rPr"), {})
            rf = rpr.makeelement(qn("w:rFonts"), {})
            rf.set(qn("w:ascii"), BODY_ASCII)
            rf.set(qn("w:hAnsi"), BODY_ASCII)
            rf.set(qn("w:eastAsia"), "黑体")
            rpr.append(rf)
            rpr.append(rpr.makeelement(qn("w:b"), {}))
            s = rpr.makeelement(qn("w:sz"), {})
            s.set(qn("w:val"), "24")
            rpr.append(s)
            t = rpr.makeelement(qn("w:t"), {})
            t.set(qn("xml:space"), "preserve")
            t.text = new_text
            r.append(rpr)
            r.append(t)
            p.append(r)

    inserted = 0
    missing = []
    for key, blocks in CONTENT.items():
        target = next((p for p in list(body.iter(qn("w:p"))) if para_text(p).strip() == key), None)
        if target is None:
            missing.append(key)
            continue
        anchor = target
        for blk in blocks:
            kind = blk[0]
            if kind == "p":
                np_ = new_body_p(skeleton, blk[1])
            elif kind == "b":
                np_ = new_body_p(skeleton, blk[1], bold_head=blk[2])
            else:
                np_ = new_body_p(skeleton, blk[1], gray=True, indent=False)
            anchor.addnext(np_)
            anchor = np_
            inserted += 1

    for p in list(body.iter(qn("w:p"))):
        if para_text(p).startswith("提交日期："):
            p.addprevious(new_body_p(skeleton, "赵龙飞 / 个人开发者（无挂靠单位）/ 产品定义、架构、前后端、设计、测试全程",
                                     bold_head="团队成员："))
            inserted += 1
            break

    doc.save(OUT)

    # ── 自检：概述字数 + 禁词（微信大赛口径不许残留）──
    chk = Document(OUT)
    on = False
    overview = 0
    for p in chk.paragraphs:
        t = p.text.strip()
        szs = {v.get(qn("w:val")) for v in p._p.iter(qn("w:sz"))}
        if "28" in szs:
            if t.startswith("一、"):
                on = True
                continue
            if on and t.startswith("二、"):
                break
        if on and "24" not in szs:
            overview += len(t)

    full = "\n".join(p.text for p in chk.paragraphs)
    # 禁的是"平台免费送资源"那一类话（这是移动的比赛）。模型与平台的真实名字要写，不在禁词里。
    banned = [w for w in ("免费额度", "成长计划", "10 亿 Token", "亿Token", "感谢微信", "微信把",
                          "算力与流量入口", "都提供了免费版本", "国民级入口",
                          "把最大的那块成本消掉", "零账单", "免费 AI") if w in full]

    print("删除灰色说明行:", removed)
    print("封面已填:", "、".join(filled))
    print("插入正文段:", inserted)
    if missing:
        print("!! 没找到这些小标题（模板改过）:", missing, file=sys.stderr)
        sys.exit(2)
    ok_len = OVERVIEW_MIN <= overview <= OVERVIEW_MAX
    print(f"一、作品概述 正文字数: {overview} → {'在 200–500 内' if ok_len else '超出模板要求'}")
    print("禁词命中:", banned if banned else "零命中")
    print("全文总字数:", sum(len(p.text.strip()) for p in chk.paragraphs))
    print("输出:", OUT)
    if not ok_len or banned:
        sys.exit(3)


if __name__ == "__main__":
    main()
