def para_text(p):
    return "".join(n.text or "" for n in p.iter(qn("w:t")))


def is_gray_instruction(p):
    szs = {v.get(qn("w:val")) for v in p.iter(qn("w:sz"))}
    cols = {v.get(qn("w:val")) for v in p.iter(qn("w:color"))}
    return "21" in szs and "808080" in cols


def new_body_p(template_p, text, *, bold_head=None, indent=True, gray=False):
    p = copy.deepcopy(template_p)
    for r in list(p.findall(qn("w:r"))):
        p.remove(r)
    for h in list(p.findall(qn("w:hyperlink"))):
        p.remove(h)
    ppr = p.find(qn("w:pPr"))
    if ppr is None:
        ppr = p.makeelement(qn("w:pPr"), {})
        p.insert(0, ppr)
    ind = ppr.find(qn("w:ind"))
    if ind is not None and not indent:
        ppr.remove(ind)
    # 骨架段本身是灰色说明行，pPr 里的段落标记带着 color=808080；不清掉每段正文的段落符都是灰的。
    mrpr = ppr.find(qn("w:rPr"))
    if mrpr is not None:
        ppr.remove(mrpr)

    def add(txt, bold):
        r = p.makeelement(qn("w:r"), {})
        rpr = r.makeelement(qn("w:rPr"), {})
        rf = rpr.makeelement(qn("w:rFonts"), {})
        rf.set(qn("w:ascii"), BODY_ASCII)
        rf.set(qn("w:hAnsi"), BODY_ASCII)
        rf.set(qn("w:eastAsia"), TBD_EA if gray else BODY_EA)
        rpr.append(rf)
        if bold:
            rpr.append(rpr.makeelement(qn("w:b"), {}))
            rpr.append(rpr.makeelement(qn("w:bCs"), {}))
        if gray:
            c = rpr.makeelement(qn("w:color"), {})
            c.set(qn("w:val"), "808080")
            rpr.append(c)
        for tag in ("w:sz", "w:szCs"):
            s = rpr.makeelement(qn(tag), {})
            s.set(qn("w:val"), str(BODY_SZ))
            rpr.append(s)
        t = rpr.makeelement(qn("w:t"), {})
        t.set(qn("xml:space"), "preserve")
        t.text = txt
        r.append(rpr)
        r.append(t)
        p.append(r)

    def add_rich(txt, base_bold):
        # 源稿里的 **…** 是强调标记，落到 Word 必须变成真加粗，不许留星号。
        parts = txt.split("**")
        for k, seg in enumerate(parts):
            if seg:
                add(seg, base_bold if k % 2 == 0 else not base_bold)

    if bold_head:
        add(bold_head, True)
        add_rich(text, False)
    else:
        add_rich(text, False)
    return p


