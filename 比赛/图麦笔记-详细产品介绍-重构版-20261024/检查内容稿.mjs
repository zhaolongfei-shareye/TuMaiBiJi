import {chromium} from '/Users/zlfmac/.npm/_npx/9833c18b2d85bc59/node_modules/playwright/index.mjs';
import {writeFile} from 'node:fs/promises';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=dirname(fileURLToPath(import.meta.url));
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5097/'+encodeURIComponent('详细产品介绍-内容核对稿.html'));
  await page.evaluate(()=>document.fonts.ready);
  await page.locator('img').evaluateAll(imgs=>Promise.all(imgs.map(i=>i.decode())));
  const imagesDecoded=await page.locator('.designs img').count();
  if(imagesDecoded!==4)throw new Error('Expected four travel opening pages');
  const previewLinks=await page.locator('.designs figure a').evaluateAll(links=>links.map(a=>decodeURIComponent(a.getAttribute('href'))));
  if(previewLinks.some(href=>!href.startsWith('瑞士故事版图片/')))throw new Error('Retired preview referenced');
  const sections=await page.locator('.chapter').count();
  const features=await page.locator('.feature').count();
  if(sections!==12||features!==77) throw new Error('Content count mismatch');
  const missing=await page.locator('.feature').evaluateAll(items=>items.filter(a=>a.querySelectorAll('.para').length!==4||!a.querySelector('details')).map(a=>a.id));
  if(missing.length)throw new Error(JSON.stringify(missing));
  await page.locator('#search').fill('图片笔记');
  const searchHits=await page.locator('.feature:not(.hide)').count();
  if(searchHits<1||!await page.locator('#f-02-06').isVisible())throw new Error('Search failed');
  await page.locator('#search').fill('没有匹配结果的测试词xyz');
  if(await page.locator('.feature:not(.hide)').count()||!await page.locator('.no-results').isVisible())throw new Error('Empty search failed');
  await page.locator('#clear').click();
  await page.locator('aside a[href="#c06"]').click();
  await page.waitForFunction(()=>Math.abs(document.querySelector('#c06').getBoundingClientRect().top-document.querySelector('header').offsetHeight-20)<3);
  await page.locator('#f-06-03 details summary').click();
  if(!await page.locator('#f-06-03 details').getAttribute('open').then(x=>x!==null))throw new Error('Source disclosure failed');
  await page.locator('#f-06-03').screenshot({path:join(root,'图文卡内容核对.png')});
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:join(root,'内容稿桌面预览.png')});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  const mobile=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
  if(mobile.scrollWidth>mobile.width)throw new Error('Mobile overflow');
  await page.screenshot({path:join(root,'内容稿手机预览.png')});
  await page.locator('aside a[href="#c01"]').click();
  await page.waitForFunction(()=>Math.abs(document.querySelector('#c01').getBoundingClientRect().top-document.querySelector('header').offsetHeight-20)<3);
  if(errors.length)throw new Error(JSON.stringify(errors));
  const report={result:'PASS',chapters:sections,items:features,paragraph_blocks:features*4,searchHits,emptySearch:true,clearSearch:true,chapterNavigation:true,sourceDisclosure:true,imagesDecoded,previewLinks,mobile,errors};
  await writeFile(join(root,'内容稿浏览检查.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
} finally {await browser.close()}
