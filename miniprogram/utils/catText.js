/* 分类名的显示口径（站长 10-17 原话「分类名称是中文，切换英文，自动翻译；分类是英文，
   切换中文，也是自动翻译。如果翻译不了，就维持原文」）。
   "那一档留空就回落原文"这一支只该有一份实现：列表那一排、录入页那枚选择器、详情窗、
   海报上那行小字四处各写一遍，迟早只有一处成立。
   ⚠ 这个函数只管**给人看**。重名判据、私密判据、删格归未分类那些一律读 `cat.name`，
   那是他自己打的字、是身份；把译文写回 `name` 等于我改了他的分类名。
   ⚠ 文件名不叫 catLabel：`验-列表D2` 有一条全仓扫退役名 `catLabel` 的反向判据（那是 v18 就撤掉的
   "点 + 分类名 + meta 行"那一排的变量名），撞上这个名字就把那一把判红一次。 */
function labelOf(cat, lang) {
  if (!cat) return ''
  const one = lang === 'zh' ? cat.name_zh : cat.name_en
  return one || cat.name || ''
}

module.exports = { labelOf }
