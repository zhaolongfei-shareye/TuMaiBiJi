function t(key, lang) {
  const dict = i18n[lang] || i18n.zh
  return dict[key] || i18n.zh[key] || key
}

// WXML 表达式不能调用 JS 函数，页面需把预计算的文案映射放进 data，
// 模板里用 {{t.key}} 取值；en 缺失的 key 回退到 zh。
function texts(lang) {
  return Object.assign({}, i18n.zh, i18n[lang] || {})
}

module.exports = { i18n, t, texts }
